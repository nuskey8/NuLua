use std::collections::BTreeSet;
use std::fmt::Write;
use std::path::Path;

// Only scan modules linked by native/Makefile. Analysis and CodeGen flags are
// not available in the shipped VM/compiler library.
pub fn generate(root: &Path) {
    let mut boolean = BTreeSet::new();
    let mut integer = BTreeSet::new();
    for module in ["Ast", "Compiler", "VM", "Bytecode", "Common"] {
        let dir = root.join("submodules/luau").join(module).join("src");
        println!("cargo:rerun-if-changed={}", dir.display());
        for entry in std::fs::read_dir(dir).expect("read Luau sources") {
            let path = entry.expect("read source entry").path();
            if path.extension().and_then(|x| x.to_str()) != Some("cpp") {
                continue;
            }
            let source = std::fs::read_to_string(path).expect("read Luau source");
            for line in source.lines().map(str::trim) {
                let Some((declaration, rest)) = line.split_once('(') else {
                    continue;
                };
                let flags = match declaration {
                    "LUAU_FASTFLAGVARIABLE" | "LUAU_DYNAMIC_FASTFLAGVARIABLE" => &mut boolean,
                    "LUAU_FASTINTVARIABLE" | "LUAU_DYNAMIC_FASTINTVARIABLE" => &mut integer,
                    _ => continue,
                };
                let name = rest.split([',', ')']).next().unwrap().trim();
                assert!(name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'));
                flags.insert(name.to_owned());
            }
        }
    }

    let mut output = String::from(
        "// <auto-generated />\n// Generated by native/luau/feature_flags.rs from the bundled Luau sources.\nnamespace NuLua.Luau;\n\npublic static unsafe partial class LuauFeatureFlags\n{\n",
    );
    let mut members = BTreeSet::new();
    for flags in [&boolean, &integer] {
        for name in flags {
            assert!(members.insert(name), "duplicate flag property");
            writeln!(
                output,
                "    public static ReadOnlySpan<byte> {name} => \"{name}\"u8;\n"
            )
            .unwrap();
        }
    }
    output.push_str("}\n");
    let dir = root.join("src/NuLua.Luau/Generated");
    std::fs::create_dir_all(&dir).expect("create generated directory");
    std::fs::write(dir.join("LuauFeatureFlags.g.cs"), output).expect("write feature flags");
    println!("cargo:rerun-if-changed=feature_flags.rs");
}
